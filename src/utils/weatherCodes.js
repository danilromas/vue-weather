export function describe(code, isDay = 1) {
  const [text, icon, group] = codes[code] ?? ['—', '🌡️', 'clouds']
  // ночью вместо солнца — луна
  if (!isDay && group === 'clear') return { text, icon: '🌙', group: 'night' }
  return { text, icon, group }
}
